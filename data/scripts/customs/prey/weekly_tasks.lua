local function hasDifficulty(entry, difficulty)
    if type(entry.difficulties) ~= "table" then
        return tonumber(entry.difficulties) == difficulty
    end
    for _, allowed in ipairs(entry.difficulties) do
        if tonumber(allowed) == difficulty then
            return true
        end
    end
    return false
end

local function buildMonsterTasks(difficulty)
    local range = killRanges[difficulty] or killRanges[1]
    local tasks = {}
    for _, monster in ipairs(bountyMonsters or {}) do
        if hasDifficulty(monster, difficulty) then
            tasks[#tasks + 1] = {
                raceId = monster.raceId,
                name = monster.name,
                minTotal = range[1],
                maxTotal = range[2],
            }
        end
    end
    return tasks
end

local function appendDeliveryTasks(tasks, source, range)
    for _, item in ipairs(source or {}) do
        tasks[#tasks + 1] = {
            itemId = item.itemId,
            minTotal = range[1],
            maxTotal = range[2],
        }
    end
end

local function buildDeliveryTasks(difficulty)
    local tasks = {}
    appendDeliveryTasks(tasks, deliveryItems.equipment, deliveryRanges.equipment[difficulty] or deliveryRanges.equipment[1])
    appendDeliveryTasks(tasks, deliveryItems.resource, deliveryRanges.resource[difficulty] or deliveryRanges.resource[1])
    return tasks
end

