local ornamentsById = {}
local ornamentsByStorage = {}
for _, ornament in ipairs(OrnamentSystem.ornaments) do
    ornamentsById[ornament.id] = ornament
    ornamentsByStorage[ornament.storage] = ornament
end

local function isUnlocked(player, ornament)
    return ornament and player:getStorageValue(ornament.storage) >= 1
end

local function sendUnlockMessage(player, ornament)
    if not player or not ornament then
        return
    end

    player:sendTextMessage(MESSAGE_INFO_DESCR, string.format("You have unlocked a new ornament called %s.", ornament.name))
end

local function getSelectedId(player)
    local selectedId = math.max(0, player:getStorageValue(OrnamentSystem.selectedStorage))
    local ornament = ornamentsById[selectedId]
    if not isUnlocked(player, ornament) then
        return 0
    end
    return selectedId
end

local function getApplyPayload(player)
    local selectedId = getSelectedId(player)
    local ornament = ornamentsById[selectedId]
    return {
        action = "apply",
        creatureId = player:getId(),
        ornamentId = selectedId,
        image = ornament and ornament.image or "",
    }
end

local function sendJson(receiver, payload)
    if not receiver or not payload then
        return
    end

    local buffer = json.encode(payload)
    if type(buffer) ~= "string" or buffer == "" then
        return
    end

    local chunkSize = OrnamentSystem.chunkSize or 8000
    if #buffer <= chunkSize then
        receiver:sendExtendedOpcode(OrnamentSystem.opcode, buffer)
        return
    end

    local parts = {}
    for index = 1, #buffer, chunkSize do
        parts[#parts + 1] = buffer:sub(index, index + chunkSize - 1)
    end

    receiver:sendExtendedOpcode(OrnamentSystem.opcode, "S" .. parts[1])
    for index = 2, #parts - 1 do
        receiver:sendExtendedOpcode(OrnamentSystem.opcode, "P" .. parts[index])
    end
    receiver:sendExtendedOpcode(OrnamentSystem.opcode, "E" .. parts[#parts])
end

local function sendApply(receiver, subject)
    sendJson(receiver, getApplyPayload(subject))
end

local function broadcastSelection(player)
    for _, receiver in ipairs(Game.getPlayers()) do
        sendApply(receiver, player)
    end
end

local function sendOnlineSelections(receiver)
    if not receiver then
        return
    end

    for _, subject in ipairs(Game.getPlayers()) do
        sendApply(receiver, subject)
    end
end

local function sendState(player)
    local catalog = {}
    for _, ornament in ipairs(OrnamentSystem.ornaments) do
        catalog[#catalog + 1] = {
            id = ornament.id,
            name = ornament.name,
            description = ornament.description,
            image = ornament.image,
            unlocked = isUnlocked(player, ornament),
        }
    end

    local visiblePlayers = {}
    -- One bounded nearby snapshot is sent only when this player opens the ornament panel.
    local spectators = Game.getSpectators(player:getPosition(), false, true, 16, 16, 12, 12)
    for _, subject in ipairs(spectators) do
        visiblePlayers[#visiblePlayers + 1] = getApplyPayload(subject)
    end

    sendJson(player, {
        action = "state",
        ornaments = catalog,
        selectedId = getSelectedId(player),
        players = visiblePlayers,
    })
end

function OrnamentSystem.unlock(player, ornamentId)
    local ornament = ornamentsById[tonumber(ornamentId) or 0]
    if not player or not ornament then
        return false
    end

    local wasUnlocked = isUnlocked(player, ornament)
    player:setStorageValue(ornament.storage, 1)
    if not wasUnlocked then
        sendUnlockMessage(player, ornament)
    end
    sendState(player)
    return true
end

function OrnamentSystem.notifyStorageUnlock(player, storage, oldValue, newValue)
    local ornament = ornamentsByStorage[tonumber(storage) or 0]
    if not player or not ornament then
        return false
    end

    if (tonumber(oldValue) or -1) < 1 and (tonumber(newValue) or -1) >= 1 then
        sendUnlockMessage(player, ornament)
        sendState(player)
        return true
    end

    return false
end

function OrnamentSystem.lock(player, ornamentId)
    local ornament = ornamentsById[tonumber(ornamentId) or 0]
    if not player or not ornament then
        return false
    end

    player:setStorageValue(ornament.storage, -1)
    if getSelectedId(player) == 0 then
        player:setStorageValue(OrnamentSystem.selectedStorage, 0)
        broadcastSelection(player)
    end
    sendState(player)
    return true
end

_G.OrnamentSystem = OrnamentSystem

local extendedEvent = CreatureEvent("OrnamentExtendedOpcode")

function extendedEvent.onExtendedOpcode(player, opcode, buffer)
    if opcode ~= OrnamentSystem.opcode then
        return
    end

    local ok, request = pcall(json.decode, buffer)
    if not ok or type(request) ~= "table" then
        return
    end

    if request.action == "open" or request.action == "refresh" then
        sendState(player)
        return
    end

    if request.action == "set" then
        local ornamentId = tonumber(request.ornamentId) or 0
        local ornament = ornamentsById[ornamentId]
        if not isUnlocked(player, ornament) then
            player:sendCancelMessage("This ornament is still locked.")
            sendState(player)
            return
        end

        player:setStorageValue(OrnamentSystem.selectedStorage, ornamentId)
        broadcastSelection(player)
        sendState(player)
        return
    end

    if request.action == "remove" then
        player:setStorageValue(OrnamentSystem.selectedStorage, 0)
        broadcastSelection(player)
        sendState(player)
    end
end

extendedEvent:type("extendedopcode")
extendedEvent:register()

local loginEvent = CreatureEvent("OrnamentLogin")

function loginEvent.onLogin(player)
    player:registerEvent("OrnamentExtendedOpcode")
    addEvent(function(playerId)
        local onlinePlayer = Player(playerId)
        if not onlinePlayer then
            return
        end
        sendOnlineSelections(onlinePlayer)
        broadcastSelection(onlinePlayer)
    end, 1000, player:getId())
    return true
end

loginEvent:type("login")
loginEvent:register()

local logoutEvent = CreatureEvent("OrnamentLogout")

function logoutEvent.onLogout(player)
    local payload = {
        action = "apply",
        creatureId = player:getId(),
        ornamentId = 0,
        image = "",
    }
    for _, receiver in ipairs(Game.getPlayers()) do
        if receiver ~= player then
            sendJson(receiver, payload)
        end
    end
    return true
end

logoutEvent:type("logout")
logoutEvent:register()
