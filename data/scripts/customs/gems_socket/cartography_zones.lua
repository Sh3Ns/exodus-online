    zone.id = zoneId
    zone.points = math.max(0, tonumber(zone.points or zone.Points) or 0)
    GemsSocketCartography.totalPoints = GemsSocketCartography.totalPoints + zone.points

    local firstFloor = math.min(tonumber(zone.from and zone.from.z) or 0, tonumber(zone.to and zone.to.z) or 0)
    local lastFloor = math.max(tonumber(zone.from and zone.from.z) or 0, tonumber(zone.to and zone.to.z) or 0)
    for floor = firstFloor, lastFloor do
        GemsSocketCartography.zonesByFloor[floor] = GemsSocketCartography.zonesByFloor[floor] or {}
        GemsSocketCartography.zonesByFloor[floor][#GemsSocketCartography.zonesByFloor[floor] + 1] = zone
    end
end
