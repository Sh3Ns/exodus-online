CREATE TABLE IF NOT EXISTS `player_tracked_creatures` (
    `player_id`     INT(11)      NOT NULL,
    `creature_name` VARCHAR(255) NOT NULL,
    PRIMARY KEY (`player_id`, `creature_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
]])

db.query([[
CREATE TABLE IF NOT EXISTS `player_charms` (
    `player_id`    INT(11)     NOT NULL,
    `charm_id`     VARCHAR(2)  NOT NULL,
    `monster_name` VARCHAR(70),
    FOREIGN KEY (`player_id`) REFERENCES `players`(`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
]])

