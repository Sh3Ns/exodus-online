Bestiary.saveCharmMonsterSql =
	[[
  UPDATE
	`player_charms`
  SET
	`monster_name` = '%s'
  WHERE `player_id` = %d AND `charm_id` = %d; 
]]

Bestiary.deleteCharmMonsterSql =
	[[
  UPDATE
	`player_charms`
  SET
	`monster_name` = ''
  WHERE `player_id` = %d AND `charm_id` = %d; 
]]

