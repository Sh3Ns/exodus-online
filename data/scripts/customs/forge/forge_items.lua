ForgeItems.classifications = {}

for _, name in ipairs(ForgeItems.classification2Names) do
    ForgeItems.names[#ForgeItems.names + 1] = name
    ForgeItems.classifications[name] = 2
end

for _, name in ipairs(ForgeItems.classification3Names) do
    ForgeItems.names[#ForgeItems.names + 1] = name
    ForgeItems.classifications[name] = 3
end

for _, name in ipairs(ForgeItems.classification4Names) do
    ForgeItems.names[#ForgeItems.names + 1] = name
    ForgeItems.classifications[name] = 4
end

local nameSet = {}
for _, name in ipairs(ForgeItems.names) do
    nameSet[string.lower(name)] = true
end

local forgeWeaponTypes = {
    [WEAPON_SWORD] = true,
    [WEAPON_CLUB] = true,
    [WEAPON_AXE] = true,
    [WEAPON_FIST] = true,
    [WEAPON_DISTANCE] = true,
    [WEAPON_WAND] = true,
}

function ForgeItems.getEquipmentKind(itemType)
    if not itemType then return nil end

    if forgeWeaponTypes[itemType:getWeaponType()] then
        return "weapon"
    end

    local slotPosition = tonumber(itemType:getSlotPosition()) or 0
    if bit.band(slotPosition, SLOTP_HEAD) ~= 0 then return "helmet" end
    if bit.band(slotPosition, SLOTP_ARMOR) ~= 0 then return "armor" end
    if bit.band(slotPosition, SLOTP_LEGS) ~= 0 then return "legs" end
    if bit.band(slotPosition, SLOTP_FEET) ~= 0 then return "boots" end
    return nil
end

function ForgeItems.getClassification(itemType)
    local name = string.lower(itemType:getName() or "")
    return tonumber(ForgeItems.classifications[name]) or ForgeItems.defaultClassification
end

function ForgeItems.isAllowedType(itemType)
    if not itemType then return false end
    local ok, allowed = pcall(function()
        local name = string.lower(itemType:getName() or "")
        return nameSet[name] == true and
            ForgeItems.getEquipmentKind(itemType) ~= nil and
            not name:find('glove', 1, true) and
            not name:find('gauntlet', 1, true) and
            not name:find('handwrap', 1, true) and
            not name:find('belt', 1, true) and
            not name:find('badge', 1, true) and
            not name:find('deck', 1, true) and
            not name:find('boat', 1, true) and
            not itemType:isContainer() and
            not itemType:isStackable() and
            itemType:isPickupable() and
            (tonumber(itemType:getSlotPosition()) or 0) ~= 0
    end)
    return ok and allowed == true
end

function ForgeItems.getEntries()
    local entries = {}
    local seenIds = {}
    for _, name in ipairs(ForgeItems.names) do
        local ok, itemType = pcall(ItemType, name)
        local itemId = 0
        if ok and itemType then
            local idOk, idValue = pcall(function() return itemType:getId() end)
            if idOk then itemId = tonumber(idValue) or 0 end
        end
        if ok and itemId > 0 and not seenIds[itemId] and ForgeItems.isAllowedType(itemType) then
            seenIds[itemId] = true
            entries[#entries + 1] = {
                id = itemId,
                clientId = tonumber(itemType:getClientId()) or 0,
                name = itemType:getName(),
                classification = ForgeItems.getClassification(itemType)
            }
        end
    end
    table.sort(entries, function(a, b) return a.id < b.id end)
    return entries
end

return ForgeItems
